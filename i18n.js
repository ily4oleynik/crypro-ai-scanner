let currentLang = localStorage.getItem('lang') || 'ru';

function t(key) {
  return (I18N[currentLang] && I18N[currentLang][key]) || I18N.en[key] || key;
}

function setLanguage(lang) {
  if (!I18N[lang]) return;
  currentLang = lang;
  localStorage.setItem('lang', lang);
  applyTranslations();
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });
  if (typeof loadHomeWidgets === 'function') loadHomeWidgets();
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const val = t(key);
    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') el.placeholder = val;
    else el.textContent = val;
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
  });
  const authBtn = document.getElementById('auth-btn');
  if (authBtn && typeof user !== 'undefined') {
    authBtn.textContent = user ? t('nav.logout') : t('nav.login');
  }
  const authTitle = document.getElementById('auth-title');
  const authSubmit = document.getElementById('auth-submit');
  const mode = document.querySelector('.auth-tab.active')?.dataset?.mode || 'login';
  if (authTitle) authTitle.textContent = mode === 'login' ? t('auth.login') : t('auth.register');
  if (authSubmit) authSubmit.textContent = mode === 'login' ? t('auth.submitLogin') : t('auth.submitRegister');
}

window.t = t;
window.setLanguage = setLanguage;
window.applyTranslations = applyTranslations;

let currentLang = localStorage.getItem('lang') || 'ru';
if (currentLang !== 'ru' && currentLang !== 'en') currentLang = 'ru';

const I18N_ALIASES = {
  'nav.logout': 'btn.logout',
  'nav.login': 'btn.login',
  'btn.logout': 'btn.logout',
  'btn.login': 'btn.login'
};

function t(key) {
  if (I18N_ALIASES[key]) key = I18N_ALIASES[key];

  if (!key) return '';
  const lang = currentLang === 'en' ? 'en' : 'ru';
  const dict = I18N[lang] || I18N.ru;
  if (dict && dict[key] != null) return dict[key];
  if (I18N.en && I18N.en[key] != null) return I18N.en[key];
  if (I18N.ru && I18N.ru[key] != null) return I18N.ru[key];
  // never show raw keys like nav.logout
  if (typeof key === 'string' && key.indexOf('.') !== -1) {
    const last = key.split('.').pop();
    return last.charAt(0).toUpperCase() + last.slice(1);
  }
  return key;
}

function setText(sel, key) {
  const el = document.querySelector(sel);
  if (el) el.textContent = t(key);
}

function setPlaceholder(id, key) {
  const el = document.getElementById(id);
  if (el) el.placeholder = t(key);
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (!key) return;
    const val = t(key);
    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
      el.placeholder = val;
      return;
    }
    // Terms line keeps links
    if (key === 'auth.terms') {
      const ru = (typeof currentLang !== 'undefined' ? currentLang : localStorage.getItem('lang')) !== 'en';
      el.innerHTML = ru
        ? 'Согласен с <a href="/terms.html" target="_blank" rel="noopener">условиями</a> и <a href="/privacy.html" target="_blank" rel="noopener">политикой конфиденциальности</a>'
        : 'I agree to the <a href="/terms.html" target="_blank" rel="noopener">Terms</a> and <a href="/privacy.html" target="_blank" rel="noopener">Privacy Policy</a>';
      return;
    }
    el.textContent = val;
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
  });

  // Nav + drawer (ids are stable)
  setText('#nav-home', 'nav.home');
  setText('#nav-scanner', 'nav.scanner');
  setText('#nav-watchlist', 'nav.watchlist');
  setText('#nav-history', 'nav.history');
  setText('#nav-alerts', 'nav.alerts');
  setText('#nav-compare', 'nav.compare');
  setText('#nav-account', 'nav.account');
  setText('#nav-portfolio', 'nav.portfolio');

  const drawerMap = {
    'drawer-home': 'nav.home',
    'drawer-scanner': 'nav.scanner',
    'drawer-watchlist': 'nav.watchlist',
    'drawer-history': 'nav.history',
    'drawer-alerts': 'nav.alerts',
    'drawer-compare': 'nav.compare',
    'drawer-account': 'nav.account'
  };
  Object.keys(drawerMap).forEach((id) => {
    const el = document.getElementById(id);
    if (!el) return;
    const ico = el.querySelector('.d-ico');
    const label = t(drawerMap[id]);
    if (ico) el.innerHTML = ico.outerHTML + ' ' + label;
    else el.textContent = label;
  });

  setText('#nav-scan-cta', 'btn.checkToken');
  setText('#drawer-upgrade', 'btn.upgrade');
  document.querySelectorAll('.nav-actions .plan-btn, .top-nav .plan-btn').forEach((btn) => {
    if (!btn.closest('.price-card') && !btn.closest('.plans-list')) {
      btn.textContent = t('btn.upgrade');
    }
  });

  setText('#refresh-trending', 'section.refresh');
  setText('#scan-button', 'scanner.analyze');
  setText('.scanner-hero h1', 'scanner.title');
  setText('.scanner-hero > p', 'scanner.subtitle');

  setPlaceholder('auth-email', 'auth.email');
  setPlaceholder('auth-password', 'auth.password');
  setPlaceholder('auth-password2', 'auth.password2');
  setPlaceholder('token-input', 'scanner.placeholder');
  setPlaceholder('home-token-input', 'hero.placeholder');

  const termsLabel = document.querySelector('#auth-terms-wrap span, .auth-terms span');
  if (termsLabel) {
    termsLabel.innerHTML =
      currentLang === 'ru'
        ? 'Согласен с <a href="/terms.html" target="_blank">условиями</a> и <a href="/privacy.html" target="_blank">политикой</a>'
        : 'I agree to the <a href="/terms.html" target="_blank">Terms</a> and <a href="/privacy.html" target="_blank">Privacy Policy</a>';
  }

  const authBtn = document.getElementById('auth-btn');
  if (authBtn) {
    const loggedIn = typeof user !== 'undefined' && user;
    authBtn.textContent = loggedIn ? t('btn.logout') : t('btn.login');
  }
  const drawerAuth = document.getElementById('drawer-auth');
  if (drawerAuth) {
    const loggedIn = typeof user !== 'undefined' && user;
    drawerAuth.textContent = loggedIn ? t('btn.logout') : t('btn.login');
  }

  const mode = document.querySelector('.auth-tab.active')?.dataset?.mode || 'login';
  const authTitle = document.getElementById('auth-title');
  const authSubmit = document.getElementById('auth-submit');
  if (authTitle) authTitle.textContent = mode === 'login' ? t('auth.login') : t('auth.register');
  if (authSubmit) {
    authSubmit.textContent = mode === 'login' ? t('auth.submitLogin') : t('auth.submitRegister');
  }
  document.querySelectorAll('.auth-tab').forEach((tab) => {
    const m = tab.dataset.mode;
    if (m === 'login') tab.textContent = t('auth.login');
    if (m === 'register') tab.textContent = t('auth.register');
  });

  const forgot = document.getElementById('forgot-password');
  if (forgot) forgot.textContent = t('auth.forgot');

  setText('.tg-strip-label', 'tg.strip');
  setText('.tg-strip-hint', 'tg.hint');

  // Footer
  setText('#footer-scanner', 'footer.scanner');
  setText('#footer-pricing', 'footer.pricing');
  setText('#footer-alerts', 'footer.alerts');
  document.querySelectorAll('.footer-cols a[href="/methodology.html"]').forEach((a) => {
    a.textContent = t('footer.methodology');
  });
  document.querySelectorAll('.footer-cols a[href="/privacy.html"]').forEach((a) => {
    a.textContent = t('footer.privacy');
  });
  document.querySelectorAll('.footer-cols a[href="/terms.html"]').forEach((a) => {
    a.textContent = t('footer.terms');
  });
  document.querySelectorAll('.footer-bottom .muted').forEach((el) => {
    el.textContent = t('footer.payments');
  });

  // TG section on home if present
  const tgSub = document.querySelector('[data-i18n="tg.sectionSub"]');
  if (tgSub) tgSub.textContent = t('tg.sectionSub');

  // Re-render dynamic empty scanner if visible
  if (typeof renderScannerEmpty === 'function') {
    const results = document.getElementById('results');
    if (results && results.querySelector('.scanner-empty')) {
      results.innerHTML = '';
      renderScannerEmpty();
    }
  }
}

function setLanguage(lang) {
  if (lang !== 'ru' && lang !== 'en') return;
  currentLang = lang;
  localStorage.setItem('lang', lang);
  document.documentElement.lang = lang;
  document.querySelectorAll('.lang-btn').forEach((btn) => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });
  applyTranslations();
  if (typeof loadHomeWidgets === 'function') loadHomeWidgets();
  if (typeof updateAuthUI === 'function') updateAuthUI();
  // re-render current report if any
  if (window.__lastScanData && typeof renderTokenPage === 'function') {
    try {
      renderTokenPage(window.__lastScanData);
    } catch (e) {}
  }
}

window.t = t;
window.setLanguage = setLanguage;
window.applyTranslations = applyTranslations;
window.I18N = I18N;

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', applyTranslations);
} else {
  applyTranslations();
}
